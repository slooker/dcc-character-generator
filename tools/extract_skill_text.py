"""Extract each Skill/Spell's stat lines and Upgrades from dcc-skills.pdf and
dcc-spells.pdf into dist/skill-text.js, for the sheet's Skill notes and its
Skills & Spells Reference page.

Per entry:
- props: the bold "Key: value" lines under the heading (Mana Cost, Range,
  AI Favor, Cooldown, Base Damage, ...)
- upgrades: [rank, text] for each "Rank N:" line under UPGRADES

The descriptive paragraphs and flavor quotes are left out; the builder's own
notes in details.js summarize the rules.

Usage: python tools/extract_skill_text.py   (needs: pip install pymupdf)
"""
import json
import re
from pathlib import Path

import pymupdf

from extract_skill_catalog import CHAPTER_FONT, ENTRY_FONT, SECTION_FONT, spans, titlecase

ROOT = Path(__file__).resolve().parent.parent
BOLD = 'TextbookNew-Bold'
REGULAR = 'TextbookNew-Regular'
PROP = re.compile(r'^([A-Z][A-Za-z ]{1,30}):\s*(.+)$')
RANK = re.compile(r'^Rank\s*(\d)\s*(\d?)\s*:\s*(.*)$')


def clean(text: str) -> str:
    text = text.replace('‑', '-').replace('­', '')
    return re.sub(r'\s+', ' ', text).strip()


def join(parts: list[str]) -> str:
    out = ''
    for part in parts:
        # Words broken across lines end in a non-breaking hyphen ("wig-" /
        # "gle"); a real hyphen stays ("cat-" / "based").
        if out.endswith('\u2011') and part[:1].islower():
            out = out[:-1] + part
        elif out.endswith('-'):
            out += part
        else:
            out = f'{out} {part}' if out else part
    return clean(out)


LINKING = {'a', 'an', 'the', 'of', 'to', 'per', 'by', 'with', 'your', 'or', 'and', 'in', 'on', 'for', 'via', 'from', 'than', 'at', 'Earth', 'Attack'}


def continues(previous: str, text: str, font: str) -> bool:
    """Whether a line carries on the value on `previous` (the line as printed,
    with its key if it's the first). A full-width line that doesn't end a
    sentence wraps; a short one is the whole value."""
    if font.startswith(BOLD):
        return not PROP.match(text) and not text.endswith(':')
    if not font.startswith(REGULAR):
        return False
    words = previous.split()
    return (text[:1].islower() or previous.endswith(('-', '\u2011', ',', '(')) or (words and words[-1] in LINKING)
            or previous.count('(') > previous.count(')')
            or (len(previous) >= 40 and not previous.rstrip().endswith(('.', '!', '?', ')'))))


def extract(pdf_name: str) -> dict:
    doc = pymupdf.open(ROOT / 'source-files' / pdf_name)
    entries, current, mode, prop = {}, None, None, None
    for _, font, size, text in spans(doc):
        if (font.startswith(SECTION_FONT) and size == 20) or (font.startswith(CHAPTER_FONT) and size == 30):
            current = None
            continue
        if font.startswith(ENTRY_FONT) and size == 12 and text.isupper():
            if 'EXAMPLE' in text:
                current = None
                continue
            name = titlecase(re.sub(r'\s*\(.*\)$', '', text))
            current = {'props': [], 'upgrades': []}
            entries[name.lower()] = current
            mode, prop = 'head', None
            continue
        if current is None or size != 10:
            continue
        if font.startswith(BOLD) and text.strip().upper() == 'UPGRADES':
            mode = 'upgrades'
            continue
        if mode == 'upgrades':
            match = RANK.match(text) if font.startswith(BOLD) else None
            if match:
                current['upgrades'].append([int(match.group(1) + match.group(2)), [match.group(3)]])
            elif font.startswith(REGULAR) and current['upgrades']:
                current['upgrades'][-1][1].append(text)
            continue
        match = PROP.match(text) if font.startswith(BOLD) else None
        if match and mode == 'head':
            prop = [match.group(1).strip(), [match.group(2)]]
            current['props'].append(prop)
        elif prop is not None and continues(prop[1][-1] if len(prop[1]) > 1 else f'{prop[0]}: {prop[1][0]}', text, font):
            # A value that wraps onto the next line ("Base Damage: 1d2 +" /
            # "Int Electric", "Limitations: Requires two hands to wield. Each Attack" /
            # "requires proper ammunition.").
            prop[1].append(text)
        else:
            prop = None
    for entry in entries.values():
        entry['props'] = [[key, join(value)] for key, value in entry['props']]
        entry['upgrades'] = [[rank, join(text)] for rank, text in entry['upgrades']]
    return entries


if __name__ == '__main__':
    data = {**extract('dcc-skills.pdf'), **extract('dcc-spells.pdf')}
    data = {k: v for k, v in sorted(data.items()) if v['props'] or v['upgrades']}
    out = ROOT / 'dist' / 'skill-text.js'
    out.write_text(
        '// Generated by tools/extract_skill_text.py from dcc-skills.pdf and dcc-spells.pdf: each\n'
        '// Skill/Spell\'s stat lines and Upgrades, keyed by lowercased name.\n'
        f'export const skillText = {json.dumps(data, ensure_ascii=False, separators=(",", ":"))};\n',
        encoding='utf-8')
    print(f'{len(data)} entries -> {out}')
